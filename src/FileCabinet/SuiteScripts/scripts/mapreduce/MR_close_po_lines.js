  function map(context) {
    try {
      let objSearchResult = JSON.parse(context.value);

      let intPoId = objSearchResult.id;

      if (isNotEmptyOrNull(intPoId)) {
        let poRecord = record.load({
          type: record.Type.PURCHASE_ORDER,
          id: intPoId
        });

        for (let i = 0; i < poRecord.getLineCount("item"); i++) {
          let isClosed = poRecord.getSublistValue({
            sublistId: "item",
            fieldId: "isclosed",
            line: i,
          });

          if (isClosed == false) {
            poRecord.setSublistValue({
              sublistId: "item",
              fieldId: "isclosed",
              line: i,
              value: true,
            });
          }
        }

        poRecord.save({
          enableSourcing: false,
          ignoreMandatoryFields: true
        });

        log.debug("po closed", 'po #' + intPoId);
      }
    } catch (err) {
      log.debug("error in map:", err + 'cannot close po #' + intPoId);
    }
  }

